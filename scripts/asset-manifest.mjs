// Writes src/content/asset-manifest.ts: the size and blur placeholder of every image in
// public/assets, so code can pass them to next/image like a static import.
// Run after adding, renaming or removing a file there: npm run assets:manifest
// (also run by npm run cms:organize-images). Files are read, never modified.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve("public/assets");
const out = path.resolve("src/content/asset-manifest.ts");
const IMAGE = /\.(jpe?g|png|webp|avif|gif)$/i;

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? walk(full) : IMAGE.test(e.name) ? [full] : [];
  });
}

export async function writeAssetManifest() {
  const files = walk(root).sort();
  const entries = [];
  for (const file of files) {
    const rel = path.relative(root, file).split(path.sep).join("/");
    const meta = await sharp(file).metadata();
    const width = meta.width ?? 0;
    const height = meta.pageHeight ?? meta.height ?? 0;
    // An 8px preview, as Next.js generates for static imports.
    const scale = 8 / Math.max(width, height);
    const blurWidth = Math.max(1, Math.round(width * scale));
    const blurHeight = Math.max(1, Math.round(height * scale));
    const ext = path.extname(file).slice(1).toLowerCase();
    const format = ext === "png" ? "png" : ext === "webp" ? "webp" : "jpeg";
    const blur = await sharp(file).resize(blurWidth, blurHeight).toFormat(format, { quality: 70 }).toBuffer();
    const blurDataURL = `data:image/${format};base64,${blur.toString("base64")}`;
    entries.push(`  ${JSON.stringify(rel)}: { src: ${JSON.stringify(`/assets/${rel}`)}, width: ${width}, height: ${height}, blurWidth: ${blurWidth}, blurHeight: ${blurHeight}, blurDataURL: ${JSON.stringify(blurDataURL)} },`);
  }
  const source = `// Generated by scripts/asset-manifest.mjs from public/assets. Do not edit by hand:
// run \`npm run assets:manifest\` after adding, renaming or removing a file there.
import type { StaticImageData } from "next/image";

export const assetManifest = {
${entries.join("\n")}
} as const satisfies Record<string, StaticImageData>;

export type AssetPath = keyof typeof assetManifest;

/** An image in public/assets, in the shape of a static import (served at /assets/<path>). */
export function asset(file: AssetPath): StaticImageData {
  return assetManifest[file];
}
`;
  fs.writeFileSync(out, source);
  return files.length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`asset manifest: ${await writeAssetManifest()} images`);
}
